import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

/** Every command/plugin we write carries this marker so reinstall/uninstall can find it reliably. */
export const MARK = "# prov-hook";
const LEGACY = /\bprov\b.*\bhook (claude|codex)\b|cli\.js['"]? hook (claude|codex)\b/;

const shq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

export type Integration = { name: string; file: string; status: "installed" | "removed" | "skipped"; note?: string };

type HookGroup = { matcher?: string; hooks: { type: string; command: string; timeout?: number }[] };

function readJson(f: string): any {
  if (!existsSync(f)) return {};
  const text = readFileSync(f, "utf8");
  if (!text.trim()) return {};
  try {
    return JSON.parse(text);
  } catch (e) {
    // Never clobber a config we can't parse (comments, half-written file…).
    throw new Error(`${f} is not valid JSON — fix or remove it, then rerun (${(e as Error).message})`);
  }
}

const isOurs = (cmd: string) => cmd.includes(MARK) || LEGACY.test(cmd);

/** Remove our entries from a `{hooks:{Event:[{matcher,hooks:[...]}]}}` config. */
function strip(cfg: any): void {
  for (const ev of Object.keys(cfg.hooks ?? {})) {
    const groups: HookGroup[] = cfg.hooks[ev];
    if (!Array.isArray(groups)) continue;
    cfg.hooks[ev] = groups
      .map((g) => ({ ...g, hooks: (g.hooks ?? []).filter((h) => !isOurs(String(h.command ?? ""))) }))
      .filter((g) => g.hooks.length);
    if (!cfg.hooks[ev].length) delete cfg.hooks[ev];
  }
}

function hookCommand(bin: string, harness: string): string {
  // Plain `node` from PATH (survives node upgrades); --no-warnings keeps node:sqlite notices out of agent logs.
  return `node --no-warnings ${shq(bin)} hook ${harness} ${MARK}`;
}

function jsonHooks(file: string, harness: string, matcher: string, bin: string, install: boolean): Integration {
  const cfg = readJson(file);
  const before = JSON.stringify(cfg);
  strip(cfg);
  if (install) {
    cfg.hooks ??= {};
    for (const ev of ["PreToolUse", "PostToolUse"]) {
      (cfg.hooks[ev] ??= []).push({ matcher, hooks: [{ type: "command", command: hookCommand(bin, harness), timeout: 15 }] });
    }
  }
  if (!install && cfg.hooks && !Object.keys(cfg.hooks).length) delete cfg.hooks;
  if (JSON.stringify(cfg) !== before || install) writeFileSync(file, JSON.stringify(cfg, null, 2) + "\n");
  return { name: harness, file, status: install ? "installed" : "removed" };
}

/** OpenCode plugin: forwards edit-tool calls + the session's model/variant to `prov hook opencode`. */
export function opencodePlugin(bin: string): string {
  return `// ${MARK} — generated by \`prov install\`; rerun it to update, \`prov uninstall\` to remove.
import { spawn } from "node:child_process";

const PROV = ${JSON.stringify(bin)};
const EDIT_TOOLS = new Set(["edit", "write", "patch", "apply_patch", "multiedit"]);
const models = new Map(); // sessionID -> { model, effort }
const calls = new Map(); // callID -> args (older OpenCode omits args on tool.execute.after)

function send(payload) {
  return new Promise((done) => {
    try {
      const p = spawn("node", ["--no-warnings", PROV, "hook", "opencode"], { stdio: ["pipe", "ignore", "ignore"] });
      const t = setTimeout(() => { try { p.kill(); } catch {} done(); }, 15000);
      p.on("error", () => { clearTimeout(t); done(); });
      p.on("close", () => { clearTimeout(t); done(); });
      p.stdin.on("error", () => {});
      p.stdin.end(JSON.stringify(payload));
    } catch {
      done();
    }
  });
}

const server = async ({ directory }) => {
  const forward = (phase, input, args) => {
    if (!EDIT_TOOLS.has(String(input?.tool ?? "").toLowerCase())) return;
    const m = models.get(input.sessionID) ?? {};
    return send({
      hook_event_name: phase,
      session_id: input.sessionID,
      cwd: directory,
      model: m.model,
      effort: m.effort,
      tool_name: input.tool,
      tool_input: args ?? {},
    });
  };
  return {
    "chat.message": async (input) => {
      const prev = models.get(input.sessionID) ?? {};
      if (input?.model?.modelID) prev.model = input.model.providerID ? input.model.providerID + "/" + input.model.modelID : input.model.modelID;
      if (input?.variant) prev.effort = input.variant;
      models.set(input.sessionID, prev);
    },
    "chat.params": async (input, output) => {
      const prev = models.get(input.sessionID) ?? {};
      const id = input?.model?.id;
      if (id) prev.model = input.model.providerID ? input.model.providerID + "/" + id : id;
      const eff = output?.options?.reasoningEffort ?? output?.options?.reasoning_effort;
      if (typeof eff === "string" && eff) prev.effort = eff;
      models.set(input.sessionID, prev);
    },
    "tool.execute.before": async (input, output) => {
      if (input?.callID) calls.set(input.callID, output?.args);
      return forward("PreToolUse", input, output?.args);
    },
    "tool.execute.after": async (input) => {
      const args = input?.args ?? calls.get(input?.callID);
      calls.delete(input?.callID);
      return forward("PostToolUse", input, args);
    },
  };
};

export const ProvPlugin = server;
export default { id: "prov", server };
`;
}

function opencode(dir: string, bin: string, install: boolean): Integration {
  const pluginsDir = join(dir, "plugins");
  const file = join(pluginsDir, "prov.js");
  // Legacy singular dir is still scanned by OpenCode; never leave a second copy there.
  const legacy = join(dir, "plugin", "prov.js");
  for (const f of [file, legacy]) {
    if (existsSync(f) && readFileSync(f, "utf8").includes(MARK)) rmSync(f);
  }
  if (install) {
    mkdirSync(pluginsDir, { recursive: true });
    writeFileSync(file, opencodePlugin(bin));
  }
  return { name: "opencode", file, status: install ? "installed" : "removed" };
}

export type Targets = { home?: string; opencodeDir?: string };

/** Install (or remove) adapters for every agent whose config dir exists. */
export function integrate(bin: string, install: boolean, t: Targets = {}): Integration[] {
  const home = t.home ?? homedir();
  const out: Integration[] = [];
  const claudeDir = process.env.CLAUDE_CONFIG_DIR ?? join(home, ".claude");
  const codexDir = process.env.CODEX_HOME ?? join(home, ".codex");
  const ocDir = t.opencodeDir ?? process.env.OPENCODE_CONFIG_DIR ?? join(process.env.XDG_CONFIG_HOME ?? join(home, ".config"), "opencode");

  const run = (name: string, dir: string, file: string, fn: () => Integration) => {
    if (!existsSync(dir)) return out.push({ name, file, status: "skipped", note: `${dir} not found` });
    try {
      out.push(fn());
    } catch (e) {
      out.push({ name, file, status: "skipped", note: (e as Error).message });
    }
  };
  const claudeFile = join(claudeDir, "settings.json");
  run("claude", claudeDir, claudeFile, () => jsonHooks(claudeFile, "claude", "Edit|MultiEdit|Write|NotebookEdit", bin, install));
  const codexFile = join(codexDir, "hooks.json");
  run("codex", codexDir, codexFile, () => jsonHooks(codexFile, "codex", "apply_patch|Edit|Write", bin, install));
  run("opencode", ocDir, join(ocDir, "plugins", "prov.js"), () => opencode(ocDir, bin, install));
  return out;
}
